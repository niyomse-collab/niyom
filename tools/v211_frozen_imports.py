"""Filesystem-only discovery of dynamic Python imports for PyInstaller specs.

Unlike PyInstaller collect_submodules, this helper never imports the packages
being scanned. That matters for legacy BasicSR 1.4.2, whose package initializer
imports a TorchVision path removed in modern TorchVision. The runtime
compatibility hook remains responsible for that legacy import.
"""
from __future__ import annotations

from pathlib import Path


def discover_package_modules(package_root: Path, package_name: str) -> list[str]:
    """Return dotted module names for every Python source below a package root.

    This is intentionally static: no package initializer or child module is
    executed during discovery. __init__.py maps to its containing package,
    and generated bytecode/cache directories are ignored.
    """
    root = Path(package_root).resolve()
    name = str(package_name).strip()
    if not name or any(not part.isidentifier() for part in name.split(".")):
        raise ValueError("package_name must be a dotted Python identifier")
    if not root.is_dir():
        raise ValueError("package_root must be an existing directory")

    modules: set[str] = set()
    for source in root.rglob("*.py"):
        relative = source.relative_to(root)
        if "__pycache__" in relative.parts:
            continue
        parts = list(relative.with_suffix("").parts)
        if not parts:
            continue
        if parts[-1] == "__init__":
            parts.pop()
        if any(not part.isidentifier() for part in parts):
            continue
        suffix = ".".join(parts)
        modules.add(name if not suffix else name + "." + suffix)
    return sorted(modules)
