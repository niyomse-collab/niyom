"""Regression checks for experimental NiyomSilp model and training rights inventory."""
from __future__ import annotations

import csv
import hashlib
from pathlib import Path

import pytest

torch = pytest.importorskip("torch")
pytest.importorskip("numpy")
from PIL import Image

from native_models.niyomsil_sr import MODEL_ID, create_model
from native_models.train_sr import load_inventory, train


@pytest.mark.parametrize("scale", [2, 4])
def test_rgb_upscale_dimensions_and_bounded_range(scale):
    model = create_model(scale=scale, channels=8, blocks=1).eval()
    with torch.no_grad():
        result = model(torch.rand((1, 3, 9, 13)))
    assert result.shape == (1, 3, 9 * scale, 13 * scale)
    assert 0 <= float(result.min()) <= float(result.max()) <= 1


def _inventory(tmp_path, *, duplicate=False):
    folder = tmp_path / "photos"
    folder.mkdir()
    rows = []
    for split, color in (("train", (80, 140, 190)), ("val", (190, 80, 140))):
        path = folder / f"{split}.png"
        Image.new("RGB", (32, 32), color if not duplicate else (80, 140, 190)).save(path)
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        rows.append({
            "relative_path": path.name, "rights_holder": "Test fixture",
            "license": "shop-owned-test-fixture", "rights_proof": "Synthetic colors generated by test",
            "sha256": digest, "split": split,
        })
    manifest = tmp_path / "inventory.csv"
    with manifest.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    return folder, manifest


def test_manifest_requires_rights_and_isolation(tmp_path):
    folder, manifest = _inventory(tmp_path)
    result = load_inventory(manifest, folder)
    assert len(result["train"]) == len(result["val"]) == 1
    # Cannot quietly use mismatched images after their checksum changes.
    Image.new("RGB", (32, 32), (1, 2, 3)).save(folder / "train.png")
    with pytest.raises(ValueError, match="SHA256"):
        load_inventory(manifest, folder)


def test_duplicate_data_across_splits_is_rejected(tmp_path):
    folder, manifest = _inventory(tmp_path, duplicate=True)
    with pytest.raises(ValueError, match="data leakage"):
        load_inventory(manifest, folder)


def test_small_cpu_training_creates_provenance(tmp_path):
    import json
    from types import SimpleNamespace
    folder, manifest = _inventory(tmp_path)
    args = SimpleNamespace(
        data_dir=str(folder), manifest=str(manifest), output_dir=str(tmp_path / "out"),
        scale=2, epochs=1, batch_size=1, patch=16, channels=8, blocks=1,
        lr=0.0001, seed=20261011, device="cpu",
    )
    train(args)
    record = json.loads((tmp_path / "out" / "TRAINING_PROVENANCE.json").read_text("utf-8"))
    assert record["model_id"] == MODEL_ID
    assert record["status"] == "experimental_NOT_approved_for_production"
    assert record["training_origin"] == "random_initialization_no_upstream_checkpoint"
    assert (tmp_path / "out" / record["checkpoint"]).is_file()
