"""Local dataset preparation must avoid duplicates, unlicensed data and path leaks."""
from __future__ import annotations

import csv
from pathlib import Path

import pytest
from PIL import Image
from PIL.PngImagePlugin import PngInfo

from native_models.prepare_dataset import generate, write_manifests


def _dataset(tmp_path):
    root = tmp_path / "private-photos"
    for category, colors in (
        ("thai_text", [(30, 60, 90), (40, 70, 95), (50, 80, 100)]),
        ("flat_color", [(10, 50, 90), (40, 20, 85), (90, 150, 10)]),
    ):
        folder = root / category
        folder.mkdir(parents=True)
        for idx, color in enumerate(colors):
            Image.new("RGB", (64, 64), color).save(folder / f"{idx}.png")
    evidence = tmp_path / "private-evidence.txt"
    evidence.write_text("Synthetic images generated by tests. No customers.", "utf-8")
    return root, evidence


def test_generator_creates_reproducible_private_splits(tmp_path):
    root, evidence = _dataset(tmp_path)
    first = generate(root, "Fixture owner", "test-only", evidence, seed=3)
    again = generate(root, "Fixture owner", "test-only", evidence, seed=3)
    assert first == again
    assert len(first) == 6
    assert all(r["rights_proof"].startswith("SHA256:") for r in first)
    for category in ("thai_text", "flat_color"):
        split = {r["split"] for r in first if r["category"] == category}
        assert split == {"train", "val"}
    all_csv, val_csv = tmp_path / "all.csv", tmp_path / "val.csv"
    write_manifests(first, all_csv, val_csv)
    with all_csv.open("r", newline="", encoding="utf-8") as stream:
        full = list(csv.DictReader(stream))
    with val_csv.open("r", newline="", encoding="utf-8") as stream:
        validation = list(csv.DictReader(stream))
    assert len(full) == 6 and len(validation) == 2
    assert all(row["split"] == "val" for row in validation)
    with pytest.raises(FileExistsError, match="overwrite"):
        write_manifests(first, all_csv, val_csv)


def test_generator_refuses_missing_evidence(tmp_path):
    root, evidence = _dataset(tmp_path)
    evidence.unlink()
    with pytest.raises(FileNotFoundError, match="evidence"):
        generate(root, "Fixture", "test-only", evidence)


def test_generator_refuses_unknown_licensing(tmp_path):
    root, evidence = _dataset(tmp_path)
    with pytest.raises(ValueError, match="licensing"):
        generate(root, "Fixture", "", evidence)


def test_generator_rejects_duplicate_content(tmp_path):
    root, evidence = _dataset(tmp_path)
    (root / "flat_color" / "duplicate.png").write_bytes(
        (root / "thai_text" / "0.png").read_bytes()
    )
    with pytest.raises(ValueError, match="Duplicate"):
        generate(root, "Fixture", "test-only", evidence)


def test_generator_rejects_unclassified_files(tmp_path):
    root, evidence = _dataset(tmp_path)
    Image.new("RGB", (64, 64), "black").save(root / "without-category.png")
    with pytest.raises(ValueError, match="category folder"):
        generate(root, "Fixture", "test-only", evidence)


def test_generator_rejects_leaking_symlink(tmp_path):
    root, evidence = _dataset(tmp_path)
    external = tmp_path / "outside.png"
    Image.new("RGB", (64, 64), "white").save(external)
    link = root / "thai_text" / "outside.png"
    try:
        link.symlink_to(external)
    except (OSError, NotImplementedError):
        pytest.skip("Symlinks not available")
    with pytest.raises(ValueError, match="Unsafe"):
        generate(root, "Fixture", "test-only", evidence)


def test_generator_rejects_identical_pixels_with_different_png_metadata(tmp_path):
    root, evidence = _dataset(tmp_path)
    original = root / "thai_text" / "0.png"
    copy = root / "flat_color" / "different-metadata.png"
    info = PngInfo()
    info.add_text("note", "new PNG metadata, same pixels")
    with Image.open(original) as im:
        im.save(copy, pnginfo=info)
    assert original.read_bytes() != copy.read_bytes()
    with pytest.raises(ValueError, match="Duplicate decoded image pixels"):
        generate(root, "Fixture", "test-only", evidence)


def test_generator_rejects_transparency_without_explicit_flattening(tmp_path):
    root, evidence = _dataset(tmp_path)
    transparent = Image.new("RGBA", (64, 64), (255, 0, 0, 255))
    transparent.putpixel((4, 4), (255, 0, 0, 0))
    transparent.save(root / "thai_text" / "transparent.png")
    with pytest.raises(ValueError, match="Transparent training image"):
        generate(root, "Fixture", "test-only", evidence)


def test_generator_accepts_fully_opaque_rgba(tmp_path):
    root, evidence = _dataset(tmp_path)
    (root / "logo").mkdir()
    Image.new("RGBA", (64, 64), (255, 80, 90, 255)).save(
        root / "logo" / "opaque.png"
    )
    Image.new("RGB", (64, 64), (255, 80, 91)).save(
        root / "logo" / "other.png"
    )
    rows = generate(root, "Fixture", "test-only", evidence)
    assert sum(r["category"] == "logo" for r in rows) == 2
