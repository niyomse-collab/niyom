"""Deterministic tests for v2 image-quality benchmarking (without training or torch)."""
from __future__ import annotations

import csv
import hashlib
import json

import numpy as np
import pytest
from PIL import Image

from native_models.evaluate_sign_v2 import evaluate


def _images(tmp_path, *, identical=False, wrong_shape=False, split="val",
            category="thai_text"):
    root = tmp_path / "reference"
    older = tmp_path / "v1"
    newer = tmp_path / "v2"
    for path in (root, older, newer):
        path.mkdir()
    # High-contrast glyph-like bars, colored flat field and a photo-like gradient.
    yy, xx = np.indices((32, 48))
    original = np.zeros((32, 48, 3), dtype=np.uint8)
    original[:] = [234, 202, 154]
    original[6:26, 5:38] = [10, 48, 105]
    original[9:23, 9:33:6] = [235, 235, 235]
    original[25:30, :20, 0] = xx[25:30, :20] * 8
    original[25:30, :20, 1] = yy[25:30, :20] * 6
    path = "sample.png"
    Image.fromarray(original).save(root / path)
    distorted = np.clip(original.astype(np.int16) + 15, 0, 255).astype(np.uint8)
    Image.fromarray(distorted).save(older / path)
    v2 = distorted if identical else original
    if wrong_shape:
        v2 = v2[:30]
    Image.fromarray(v2).save(newer / path)
    manifest = tmp_path / "bench.csv"
    line = {
        "relative_path": path,
        "category": category,
        "split": split,
        "rights_holder": "Test fixture",
        "license": "test-only original artwork",
        "rights_proof": "Synthetic image generated by project tests",
        "sha256": hashlib.sha256((root / path).read_bytes()).hexdigest(),
    }
    with manifest.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(line))
        writer.writeheader()
        writer.writerow(line)
    return manifest, root, older, newer


def test_cleaner_candidate_is_eligible_only_for_human_review(tmp_path):
    manifest, source, v1, v2 = _images(tmp_path)
    result = evaluate(manifest, source, v1, v2)
    assert result["status"] == "eligible_for_human_print_review"
    assert result["production_approved"] is False
    assert result["image_count"] == 1
    assert result["mean_psnr_gain_db"] > 0
    assert result["by_category"]["thai_text"]["regression_count"] == 0
    assert result["images"][0]["v2"]["edge_mae"] <= result["images"][0]["v1"]["edge_mae"]
    json.dumps(result, allow_nan=False)


def test_unimproved_candidate_is_not_approved(tmp_path):
    manifest, source, v1, v2 = _images(tmp_path, identical=True)
    result = evaluate(manifest, source, v1, v2)
    assert result["status"] == "rejected_by_automated_quality_gate"
    assert result["mean_psnr_gain_db"] == 0
    assert not result["production_approved"]


def test_dimension_mismatch_fails_closed(tmp_path):
    manifest, source, v1, v2 = _images(tmp_path, wrong_shape=True)
    with pytest.raises(ValueError, match="dimensions differ"):
        evaluate(manifest, source, v1, v2)


def test_validation_split_required(tmp_path):
    manifest, source, v1, v2 = _images(tmp_path, split="train")
    with pytest.raises(ValueError, match="held-out validation"):
        evaluate(manifest, source, v1, v2)


def test_reference_tampering_rejected(tmp_path):
    manifest, source, v1, v2 = _images(tmp_path)
    Image.new("RGB", (32, 48), "white").save(source / "sample.png")
    with pytest.raises(ValueError, match="checksum mismatch"):
        evaluate(manifest, source, v1, v2)


def test_unclear_category_rejected(tmp_path):
    manifest, source, v1, v2 = _images(tmp_path, category="unknown")
    with pytest.raises(ValueError, match="category"):
        evaluate(manifest, source, v1, v2)


def test_requires_independent_folders(tmp_path):
    manifest, source, v1, v2 = _images(tmp_path)
    with pytest.raises(ValueError, match="separate directories"):
        evaluate(manifest, source, source, v2)


def test_transparent_logo_regression(tmp_path):
    manifest, source, v1, v2 = _images(tmp_path, category="logo")
    reference = Image.new("RGBA", (48, 32), (0, 0, 0, 0))
    for x in range(10, 40):
        for y in range(6, 26):
            reference.putpixel((x, y), (200, 10, 30, 255))
    reference.save(source / "sample.png")
    reference.save(v1 / "sample.png")
    flattened = Image.new("RGB", (48, 32), "white")
    flattened.paste(reference, mask=reference.getchannel("A"))
    flattened.save(v2 / "sample.png")
    with manifest.open("r", encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))
    rows[0]["sha256"] = hashlib.sha256((source / "sample.png").read_bytes()).hexdigest()
    with manifest.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    result = evaluate(manifest, source, v1, v2)
    assert result["status"] == "rejected_by_automated_quality_gate"
    assert result["images"][0]["v2"]["alpha_mae"] > 0
